// Converts the SVG files in assets/icons into Dart drawing code.
//
//   dart run scripts/gen_icons.dart
//
// Supported: <path d>, <circle>, <rect> (with rx). Path commands
// M L H V C S Q T A Z, absolute and relative. Icons are outline only,
// drawn on a 24 x 24 grid; the stroke comes from AppIcon.

import 'dart:io';

const _input = 'assets/icons';
const _output = 'lib/core/icons/app_icons.g.dart';

void main() {
  final code = generate(Directory(_input));
  File(_output).writeAsStringSync(code);
  stdout.writeln('Wrote $_output');
}

String generate(Directory dir) {
  final files = dir.listSync().whereType<File>().where((f) => f.path.endsWith('.svg')).toList()
    ..sort((a, b) => a.path.compareTo(b.path));

  final names = <String>[];
  final bodies = StringBuffer();
  for (final file in files) {
    final raw = file.uri.pathSegments.last.replaceAll('.svg', '');
    final name = _camel(raw);
    names.add(name);
    bodies
      ..writeln()
      ..writeln('void _$name(Path p) {');
    for (final line in svgToCalls(file.readAsStringSync())) {
      bodies.writeln('  $line');
    }
    bodies.writeln('}');
  }

  final out = StringBuffer()
    ..writeln('// Generated by scripts/gen_icons.dart from assets/icons. Do not edit by hand.')
    ..writeln('// ignore_for_file: prefer_const_constructors')
    ..writeln()
    ..writeln("import 'dart:ui';")
    ..writeln()
    ..writeln("import 'app_icon_data.dart';")
    ..writeln()
    ..writeln('abstract final class AppIcons {');
  for (final n in names) {
    out.writeln('  static const $n = AppIconData(_$n);');
  }
  out
    ..writeln()
    ..writeln('  static const all = <String, AppIconData>{');
  for (final n in names) {
    out.writeln("    '$n': $n,");
  }
  out
    ..writeln('  };')
    ..writeln('}')
    ..write(bodies);
  return out.toString();
}

/// Turns one SVG document into a list of `p.xxx(...)` statements.
List<String> svgToCalls(String svg) {
  final calls = <String>[];
  final element = RegExp(r'<(path|circle|rect)\b([^>]*)/?>');
  for (final m in element.allMatches(svg)) {
    final attrs = _attrs(m.group(2)!);
    switch (m.group(1)) {
      case 'path':
        calls.addAll(pathToCalls(attrs['d'] ?? ''));
      case 'circle':
        final cx = _n(attrs['cx']), cy = _n(attrs['cy']), r = _n(attrs['r']);
        calls.add('p.addOval(Rect.fromCircle(center: Offset(${_f(cx)}, ${_f(cy)}), radius: ${_f(r)}));');
      case 'rect':
        final x = _n(attrs['x']), y = _n(attrs['y']);
        final w = _n(attrs['width']), h = _n(attrs['height']), rx = _n(attrs['rx']);
        final rect = 'Rect.fromLTWH(${_f(x)}, ${_f(y)}, ${_f(w)}, ${_f(h)})';
        calls.add(
          rx == 0
              ? 'p.addRect($rect);'
              : 'p.addRRect(RRect.fromRectAndRadius($rect, const Radius.circular(${_f(rx)})));',
        );
    }
  }
  return calls;
}

/// Converts SVG path data to absolute Flutter Path calls.
List<String> pathToCalls(String d) {
  final tokens = RegExp(r'[MmLlHhVvCcSsQqTtAaZz]|-?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?')
      .allMatches(d)
      .map((m) => m.group(0)!)
      .toList();

  final out = <String>[];
  var i = 0;
  var cmd = '';
  double x = 0, y = 0, sx = 0, sy = 0;
  double? cx2, cy2; // last cubic control point, for S
  double? qx, qy; // last quadratic control point, for T

  bool isCmd(String t) => RegExp(r'^[A-Za-z]$').hasMatch(t);
  double next() => double.parse(tokens[i++]);

  while (i < tokens.length) {
    if (isCmd(tokens[i])) {
      cmd = tokens[i++];
    } else if (cmd == 'M') {
      cmd = 'L';
    } else if (cmd == 'm') {
      cmd = 'l';
    }
    final rel = cmd == cmd.toLowerCase();
    final ox = rel ? x : 0.0, oy = rel ? y : 0.0;
    final upper = cmd.toUpperCase();
    if (upper != 'C' && upper != 'S') cx2 = cy2 = null;
    if (upper != 'Q' && upper != 'T') qx = qy = null;

    switch (upper) {
      case 'M':
        x = ox + next();
        y = oy + next();
        sx = x;
        sy = y;
        out.add('p.moveTo(${_f(x)}, ${_f(y)});');
      case 'L':
        x = ox + next();
        y = oy + next();
        out.add('p.lineTo(${_f(x)}, ${_f(y)});');
      case 'H':
        x = ox + next();
        out.add('p.lineTo(${_f(x)}, ${_f(y)});');
      case 'V':
        y = oy + next();
        out.add('p.lineTo(${_f(x)}, ${_f(y)});');
      case 'C':
        final x1 = ox + next(), y1 = oy + next();
        final c2x = ox + next(), c2y = oy + next();
        x = ox + next();
        y = oy + next();
        cx2 = c2x;
        cy2 = c2y;
        out.add('p.cubicTo(${_f(x1)}, ${_f(y1)}, ${_f(c2x)}, ${_f(c2y)}, ${_f(x)}, ${_f(y)});');
      case 'S':
        final x1 = cx2 == null ? x : 2 * x - cx2;
        final y1 = cy2 == null ? y : 2 * y - cy2;
        final c2x = ox + next(), c2y = oy + next();
        x = ox + next();
        y = oy + next();
        cx2 = c2x;
        cy2 = c2y;
        out.add('p.cubicTo(${_f(x1)}, ${_f(y1)}, ${_f(c2x)}, ${_f(c2y)}, ${_f(x)}, ${_f(y)});');
      case 'Q':
        final x1 = ox + next(), y1 = oy + next();
        x = ox + next();
        y = oy + next();
        qx = x1;
        qy = y1;
        out.add('p.quadraticBezierTo(${_f(x1)}, ${_f(y1)}, ${_f(x)}, ${_f(y)});');
      case 'T':
        final x1 = qx == null ? x : 2 * x - qx;
        final y1 = qy == null ? y : 2 * y - qy;
        x = ox + next();
        y = oy + next();
        qx = x1;
        qy = y1;
        out.add('p.quadraticBezierTo(${_f(x1)}, ${_f(y1)}, ${_f(x)}, ${_f(y)});');
      case 'A':
        final rx = next(), ry = next(), rot = next();
        final large = next() != 0, sweep = next() != 0;
        x = ox + next();
        y = oy + next();
        final radius = rx == ry ? 'Radius.circular(${_f(rx)})' : 'Radius.elliptical(${_f(rx)}, ${_f(ry)})';
        final extra = [
          if (rot != 0) 'rotation: ${_f(rot)}',
          if (large) 'largeArc: true',
          'clockwise: $sweep',
        ].join(', ');
        out.add('p.arcToPoint(Offset(${_f(x)}, ${_f(y)}), radius: const $radius, $extra);');
      case 'Z':
        x = sx;
        y = sy;
        out.add('p.close();');
      default:
        throw FormatException('Unsupported path command "$cmd" in "$d"');
    }
  }
  return out;
}

Map<String, String> _attrs(String s) => {
  for (final m in RegExp(r'([\w-]+)="([^"]*)"').allMatches(s)) m.group(1)!: m.group(2)!,
};

double _n(String? s) => s == null ? 0 : double.parse(s);

String _f(double v) {
  final r = (v * 10000).round() / 10000;
  if (r == r.roundToDouble()) return r.toInt().toString();
  return r.toString();
}

String _camel(String s) {
  final parts = s.split(RegExp(r'[-_ ]+'));
  return parts.first + parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join();
}
